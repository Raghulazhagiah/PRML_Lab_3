def plot_constant_density_curves(
    X,
    mean,
    covariance,
    levels=None,
    title="Constant Density Curves"
):

    if levels is None:
        levels = [0.5, 1, 2, 3, 4, 5, 6]

    x_min = X[:, 0].min() - 2
    x_max = X[:, 0].max() + 2
    y_min = X[:, 1].min() - 2
    y_max = X[:, 1].max() + 2

    xx, yy = np.meshgrid(
        np.linspace(x_min, x_max, 300),
        np.linspace(y_min, y_max, 300)
    )

    points = np.stack(
        [xx - mean[0], yy - mean[1]],
        axis=-1
    )

    inv_cov = np.linalg.inv(covariance)

    # Mahalanobis squared distance
    mahalanobis = np.einsum(
        "...i,ij,...j->...",
        points,
        inv_cov,
        points
    )

    plt.figure(figsize=(8, 8))

    plt.scatter(
        X[:, 0],
        X[:, 1],
        s=8,
        alpha=0.25
    )

    plt.contour(
        xx,
        yy,
        mahalanobis,
        levels=levels
    )

    plt.scatter(
        mean[0],
        mean[1],
        color="black",
        marker="x",
        s=100,
        label="Mean"
    )

    plt.xlabel("$x_1$")
    plt.ylabel("$x_2$")
    plt.title(title)

    plt.axis("equal")
    plt.grid()
    plt.legend()

    plt.show()

plot_constant_density_curves(
    X,
    mean,
    covariance,
    title="Isotropic Gaussian - Constant Density Curves"
)

def plot_eigenvectors(
    X,
    mean,
    eigenvalues,
    eigenvectors,
    title="Eigenvectors"
):

    plt.figure(figsize=(8, 8))

    plt.scatter(
        X[:, 0],
        X[:, 1],
        s=8,
        alpha=0.25
    )

    # Plot eigenvectors
    for i in range(2):

        vector = eigenvectors[:, i]

        length = np.sqrt(eigenvalues[i])

        plt.arrow(
            mean[0],
            mean[1],
            vector[0] * length * 3,
            vector[1] * length * 3,
            head_width=0.15,
            length_includes_head=True
        )

        plt.text(
            mean[0] + vector[0] * length * 3,
            mean[1] + vector[1] * length * 3,
            f"$\\lambda_{i+1}={eigenvalues[i]:.2f}$"
        )

    plt.scatter(
        mean[0],
        mean[1],
        color="black",
        marker="x",
        s=100
    )

    plt.xlabel("$x_1$")
    plt.ylabel("$x_2$")
    plt.title(title)

