def estimate_covariance(X):

    n_samples = X.shape[0]
    n_features = X.shape[1]

    mean = np.zeros(n_features)

    for j in range(n_features):
        total = 0
        for i in range(n_samples):
            total += X[i][j]
        mean[j] = total / n_samples

    covariance = np.zeros((n_features, n_features))

    for i in range(n_features):
        for j in range(n_features):

            total = 0

            for k in range(n_samples):
                total += (X[k][i] - mean[i]) * (X[k][j] - mean[j])

            covariance[i][j] = total / (n_samples - 1)

    eigenvalues, eigenvectors = eig(covariance)

    eigenvalues = np.real(eigenvalues)
    eigenvectors = np.real(eigenvectors)

    idx = np.argsort(eigenvalues)[::-1]

    eigenvalues = eigenvalues[idx]
    eigenvectors = eigenvectors[:, idx]

    return mean, covariance, eigenvalues, eigenvectors

