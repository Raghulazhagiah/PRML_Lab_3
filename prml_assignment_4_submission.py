def gaussian_discriminant(X, mean, covariance):

    inv_cov = np.linalg.inv(covariance)

    sign, logdet = np.linalg.slogdet(covariance)

    diff = X - mean

    mahalanobis = np.einsum(
        "...i,ij,...j->...",
        diff,
        inv_cov,
        diff
    )

    return (
        -0.5 * logdet
        -0.5 * mahalanobis
    )



